export const GLYPH_W = 5;
export const GLYPH_H = 8;
export const ADVANCE = 6;
export const LINE_PITCH = 10;

const bitmaps = new Map<string, Uint8Array>();
for (const [ch, rows] of Object.entries(G)) {
  const bits = new Uint8Array(GLYPH_W * GLYPH_H);
  rows.split('|').forEach((row, r) => {
    for (let c = 0; c < GLYPH_W; c++) bits[r * GLYPH_W + c] = row[c] === '#' ? 1 : 0;
  });
  bitmaps.set(ch, bits);
}

/** The glyph bitmap of a character (unknown characters draw as a blank). */
export const glyph = (ch: string): Uint8Array => bitmaps.get(ch) ?? (bitmaps.get(ch.toLowerCase()) as Uint8Array) ?? (bitmaps.get(' ') as Uint8Array);

/** Width of a line of text in glyph pixels (pins). */
export const textWidth = (s: string): number => (s.length === 0 ? 0 : [...s].length * ADVANCE - 1);

/**
 * Coverage (0..1) of a line of text at a point in text pixel space: x to the right, y down, from
 * the top-left of the first glyph. Bilinear between pixel centres, so a pin that falls between two
 * pixels (every other hex row sits half a pin over) reads as a slope, not a stair.
 */
export const textCoverage = (chars: readonly string[], x: number, y: number, count: number = chars.length): number => {
  const n = Math.min(count, chars.length);
  if (y < -1 || y > GLYPH_H || x < -1 || x > n * ADVANCE) return 0;
  const fx = x - 0.5;
  const fy = y - 0.5;
  const x0 = Math.floor(fx);
  const y0 = Math.floor(fy);
  const ax = fx - x0;
  const ay = fy - y0;
  const px = (gx: number, gy: number) => {
    if (gy < 0 || gy >= GLYPH_H || gx < 0) return 0;
    const k = Math.floor(gx / ADVANCE);
    if (k >= n) return 0;
    const cx = gx - k * ADVANCE;
    if (cx >= GLYPH_W) return 0;
    return glyph(chars[k])[gy * GLYPH_W + cx];
  };
  const a = px(x0, y0);
  const b = px(x0 + 1, y0);
  const c = px(x0, y0 + 1);
  const d = px(x0 + 1, y0 + 1);
  return (a * (1 - ax) + b * ax) * (1 - ay) + (c * (1 - ax) + d * ax) * ay;
};
